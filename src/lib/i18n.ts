export const DICTIONARIES: Record<UiLang, Dictionary> = { "pt-PT": ptPT, es, en };

export function normalizeLang(value?: string | null): UiLang {
  if (value === "es" || value === "en" || value === "pt-PT") return value;
  return "pt-PT";
}

export function getDictionary(lang?: string | null): Dictionary {
  return DICTIONARIES[normalizeLang(lang)];
}
